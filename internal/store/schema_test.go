// These tests carry no `integration` tag on purpose. internal/store/schema holds
// two files that are copies of something the Go code already knows —
// 01-enums.sql restates models.EnumTypes() and 02-tables.sql is generated from
// the Bun models — and a copy that nothing compares is a copy that goes stale.
// specs/001-agent-manager-hub/data-model.md is a third copy, of the foreign-key
// set, and it goes stale the same way.
//
// The integration suite in store_test.go checks the same facts against a real
// migrated database, but that suite needs a container and CI runs only
// `go test ./...`. These guards are the ones that fail a pull request.
package store_test

