// `go test` runs with the package directory as the working directory, so this is
// the path relative to this file.
const dataModelPath = "../../specs/001-agent-manager-hub/data-model.md"

// TestDataModelDeclaresTheSameForeignKeys closes the transcription gap at the
// design end. TestEveryForeignKeyIsPresent proves the migrated database holds
// exactly wantForeignKeys; this proves data-model.md declares exactly the same
// set. Together they guard design -> list -> database at both links, and this
// link needs no container, so it is the one that fails a pull request.
func TestDataModelDeclaresTheSameForeignKeys(t *testing.T) {
	got := parseDesignForeignKeys(t, dataModelPath)

	// A parser that quietly matched nothing would make the comparison below pass
	// against an empty design, which is the failure mode a transcription check can
	// least afford. The floor is deliberately well under the real count: it fires
	// on a layout change that breaks extraction, and require.Equal pins the count.
	require.NotEmpty(t, got,
		"no foreign keys were extracted from %s at all — the table layouts have changed and this test is now vacuous", dataModelPath)
	require.GreaterOrEqual(t, len(got), 20,
		"only %d foreign keys were extracted from %s, which is too few to be a real reading of it", len(got), dataModelPath)

	want := append([]string(nil), wantForeignKeys...)
	sort.Strings(want)

	require.Equal(t, want, got,
		"data-model.md and wantForeignKeys disagree: either the design declares a foreign key the schema does not implement, or the schema grew one the design never asked for")
}

var (
	designTableRE  = regexp.MustCompile("^#{2,3}\\s+`([a-z_]+)`")
	designColumnRE = regexp.MustCompile("^`([a-z_]+)`\\s*(.*)$")
	designFKRE     = regexp.MustCompile(`\bfk\b`)
	// The optional parenthesised list is how a COMPOSITE foreign key is declared:
	// `fk (publisher_id, namespace) → publisher` on the second of its columns, and
	// nothing on the first, so it is emitted once and under the same column tuple
	// pg_constraint reports. Without it a two-column key could only be written as
	// two single-column ones, which is a different constraint.
	designTargetRE = regexp.MustCompile("\\bfk\\s*(?:\\(([a-z_, ]+)\\)\\s*)?→\\s*`?([a-z_]+)`?")
)

// parseDesignForeignKeys reads `table(column) -> target` out of data-model.md,
// whose tables come in two layouts: vertical, one column per row with the type in
// its own cell, and compact, every column of a narrow table on one row. The
// owning table is the nearest preceding backticked heading.
//
// There is deliberately NO inference of the target from the column name. The
// obvious heuristic — strip `_id` — reads override.reviewer_identity_id as
// pointing at `reviewer_identity`, a table that does not exist, when it points at
// `identity`; and it would read any future role-qualified column the same
// wrong-but-plausible way. So the design has to name the target and this fails
// when it does not.
func parseDesignForeignKeys(t *testing.T, path string) []string {
	t.Helper()

	b, err := os.ReadFile(path)
	require.NoError(t, err)

	var (
		out   []string
		table string
	)
	for _, line := range strings.Split(string(b), "\n") {
		line = strings.TrimSpace(line)

		if m := designTableRE.FindStringSubmatch(line); m != nil {
			table = m[1]
			continue
		}
		if !strings.HasPrefix(line, "|") {
			continue
		}

		cells := splitDesignRow(line)
		for i, cell := range cells {
			column, spec, ok := splitDesignCell(cell)
			if !ok {
				continue
			}
			// The vertical layout puts the type in the next cell; the compact layout
			// puts it in the same one. A next cell that names its own column is the
			// compact layout, and borrowing it would attribute a foreign key to the
			// column before it.
			if spec == "" && i+1 < len(cells) {
				if _, _, named := splitDesignCell(cells[i+1]); !named {
					spec = cells[i+1]
				}
			}
			if !designFKRE.MatchString(spec) {
				continue
			}
			require.NotEmpty(t, table, "a foreign key appears before any table heading: %s", line)

			m := designTargetRE.FindStringSubmatch(spec)
			require.NotNil(t, m,
				"%s.%s is declared `fk` without naming its target — write `fk → <table>`. "+
					"Guessing the target from the column name is what this test refuses to do: "+
					"stripping `_id` gets override.reviewer_identity_id wrong, and a plausible "+
					"wrong target is worse than a failure here", table, column)

			columns := column
			if m[1] != "" {
				columns = strings.Join(strings.Fields(strings.ReplaceAll(m[1], ",", " ")), ",")
			}
			out = append(out, fmt.Sprintf("%s(%s) -> %s", table, columns, m[2]))
		}
	}
	sort.Strings(out)

	return out
}

func splitDesignRow(line string) []string {
	cells := strings.Split(strings.Trim(line, "|"), "|")
	for i := range cells {
		cells[i] = strings.TrimSpace(cells[i])
	}
	return cells
}

// splitDesignCell reports whether the cell opens with a backticked column name,
// and returns the name and whatever follows it.
func splitDesignCell(cell string) (column, spec string, ok bool) {
	m := designColumnRE.FindStringSubmatch(cell)
	if m == nil {
		return "", "", false
	}
	return m[1], strings.TrimSpace(m[2]), true
}
